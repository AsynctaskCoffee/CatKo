// error.message ya da istemci tarafından eklenebilecek önekler
const ONEK = /^((?:ERROR|Error|Hata|HATA|P0001)\s*:\s*)/;

function cevir(s) {
  const t = TAM.get(s);
  if (t !== undefined) return t;
  for (const [re, en] of DESEN) if (re.test(s)) return s.replace(re, en);
  return null;
}

/** Bilinen Türkçe sunucu mesajını İngilizceye çevirir; bilinmiyorsa girdiyi aynen döndürür. */
// (8.11) bilinen çevirisi olmayan Türkçe metin için kalıp tabanlı İngilizce yedek (oyuncuya Türkçe yazı düşmez)
const TR_HARF = /[çğıöşüÇĞİÖŞÜ]/;
const TR_CUMLE = /(^|\s)(ve|için|yok|değil|olmalı|olmalısın|bulunamadı|zaten|geçersiz|önce|ile|bu|bir|yalnız|yalnızca|çok|daha|henüz|hedef|eşya|çanta|çantanda|yeterli|ölü|ölüsün|ölüyken)([\s.,;:!?]|$)|(maz|mez|sın|sin|sun|sün|dı|di|du|dü|ız|iz|amaz|emez|ılamaz|ilemez|lamaz|lemez)[.!]?$/i;
const KALIP = [
  [/^ölüyken/i, 'You cannot do this while dead.'], [/çok uzaks[ıi]n|uzakta\.?$/i, 'You are too far away.'], [/bulunamad[ıi]/i, 'Not found.'],
  [/^geçersiz/i, 'Invalid request.'], [/çanta.*(dolu|yer yok|boş yer)/i, 'There is no room in your inventory.'], [/noah yok|yeterli noah/i, 'You do not have enough Noah.'],
  [/yeterli mp/i, 'Not enough MP.'], [/yeterli hp/i, 'Not enough HP.'], [/seviye/i, 'Your level is too low.'], [/kullanılamaz|kullanamazsın/i, 'This cannot be used now.'],
  [/basılamaz|güçlendirilemez|yükseltilemez/i, 'This item cannot be upgraded.'], [/zaten/i, 'Already done.'], [/yalnız|yalnızca/i, 'You are not allowed to do this.'],
];
export function trYedek(text) {
  if (typeof text !== 'string' || !TR_HARF.test(text) || !TR_CUMLE.test(text)) return text;   // yalnız Türkçe cümle (Türkçe harfli oyuncu / eşya adları dokunulmaz)
  for (const [re, en] of KALIP) if (re.test(text)) return en;
  return 'The action could not be completed.';
}
export function enMesaj(text) {
  if (typeof text !== 'string' || !text) return text;
  const s = text.trim();
  let r = cevir(s);
  if (r != null) return r;
  const m = s.match(ONEK);
  if (m) { r = cevir(s.slice(m[1].length).trim()); if (r != null) return r; }
  return text;
}
